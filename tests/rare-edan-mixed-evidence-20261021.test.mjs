import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {BASELINE as counts} from "./helpers/catalogue-baseline.mjs";
import {buildFromFiles} from "../scripts/build-item-acquisition-index.mjs";

const read = name => JSON.parse(readFileSync(new URL("../data/"+name,import.meta.url), "utf8"));
const rare = read("rares.json").rares.find(x=>x.id==="dun-morogh-edan-the-howler");
const items = read("items-forever.json").items;
const index = read("item-acquisition-index.json");

test("Edan's Forever cloak and Classic-only dagger share a creature, not evidence status",()=>{
 assert.ok(rare);
 assert.equal(rare.name.en,"Edan the Howler");
 assert.equal(rare.name.fr,"Edan le Hurleur");
 assert.equal(rare.location_review.classic_numeric_id_reference,1137);
 assert.equal(rare.name_fr_status,"documented_forever");
 assert.equal(rare.coordinate_status,"classic_reference");
 assert.deepEqual(rare.points,[[39,47.5]]);
 assert.equal(rare.seen_forever,false);
 assert.deepEqual(rare.loot.map(x=>x.item_id),[3008,3225]);
 const [cloak,knife]=rare.loot;
 assert.equal(rare.loot_coverage,"notable_only_not_complete");
 assert.equal(cloak.evidence_level,"documented_forever");
 assert.equal(cloak.source_version,"forever_beta");
 assert.equal(cloak.evidence_kind,"forever_community_page");
 assert.equal(cloak.observed_build,"unknown");
 assert.equal(cloak.item_level,11);
 assert.equal(cloak.required_level,6);
 assert.equal(cloak.stats.en,"10 Armor");
 assert.equal(cloak.name.fr,"Cape en fourrure de wendigo");
 assert.equal(cloak.source_url,"https://www.wowhead.com/forever/fr/items/armor/cloaks");
 assert.equal(cloak.item_source_url,"https://www.wowhead.com/forever/item=3008/wendigo-fur-cloak");
 assert.match(cloak.evidence_note,/NOT a player loot capture/);
 assert.equal(cloak.chance_forever_observed_percent,null);
 assert.equal(knife.evidence_level,"classic_reference");
 assert.equal(knife.source_version,"classic_reference");
 assert.equal(knife.item_level,9);
 assert.equal(knife.required_level,4);
 assert.equal(knife.stats_version,"classic_reference");
 assert.equal(knife.chance_forever_observed_percent,undefined);
 assert.match(knife.evidence_note,/does not prove that the Classic NPC drop relation survives/);
 assert.equal(knife.forever_item_snapshot.item_level,11);
 assert.equal(knife.forever_item_snapshot.required_level,6);
 assert.equal(knife.forever_item_snapshot.evidence_level,"documented_forever");
 assert.equal(knife.forever_item_snapshot.source_url,"https://www.wowhead.com/forever/item=3225/bloodstained-knife");
});

test("Only Forever cloak enters editorial equipment; the Classic dagger remains explicitly Classic",()=>{
 const cloak=items.find(x=>x.id===3008);
 assert.ok(cloak);
 assert.equal(cloak.name_fr,"Cape en fourrure de wendigo");
 assert.equal(cloak.itemLevel,11);
 assert.equal(cloak.requiredLevel,6);
 assert.equal(cloak.verified_forever,false);
 assert.equal(cloak.acquisition_sources.length,1);
 assert.equal(cloak.acquisition_sources[0].kind,"rare");
 assert.equal(cloak.acquisition_sources[0].evidence_level,"documented_forever");
 assert.equal(cloak.acquisition_sources[0].source_url,rare.loot[0].source_url);
 assert.ok(!items.some(x=>x.id===3225),"Classic drop not promoted into editorial Forever equipment");
 assert.deepEqual(index,buildFromFiles());
 assert.equal(index.totals.unique_items,counts.index.uniqueItems);
 assert.equal(index.totals.relations,counts.index.relations);
 const cloakRef=index.items.find(x=>x.id===3008)?.sources[0];
 const knifeRef=index.items.find(x=>x.id===3225)?.sources[0];
 assert.equal(cloakRef.evidence_level,"documented_forever");
 assert.equal(knifeRef.evidence_level,"classic_reference");
 assert.equal(index.totals.by_evidence.classic_reference,counts.index.byEvidence.classic_reference);
 assert.equal(index.totals.by_evidence.documented_forever,counts.index.byEvidence.documented_forever);
});
